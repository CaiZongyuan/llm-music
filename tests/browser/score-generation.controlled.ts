test('Version persistence failure keeps Candidate and inputs and retries the first name despite later edits', async ({ page, baseURL }, info) => {
  const { api, project, score, original } = await withParent(baseURL);
  const selected = await selectEdited(page, project.id, score.id);
  const candidate = await generateCandidate(page);
  const path = { project_id: project.id };
  const writes: unknown[] = [];
  page.on('request', request => { if (request.method() === 'POST' && request.url().endsWith('/versions')) writes.push(request.postDataJSON()); });
  await page.getByRole('textbox', { name: 'Version name', exact: true }).fill('First name after storage failure');
  await writeFile(resolve(runDir!, 'fail-version-save'), 'owned CPU test fault');
  await page.getByRole('button', { name: 'Save as a version', exact: true }).click();
  await expect(page.locator('.save-candidate .error-box')).toContainText('version_commit_unconfirmed');
  expect(received(await api.GET('/projects/{project_id}/versions', { params: { path } }))).toEqual([original]);
  await expect(page.locator('.candidate-detail')).toHaveAttribute('data-candidate-id', candidate);
  await expect(page.getByRole('textbox', { name: 'ABC Score text', exact: true })).toHaveValue(EDITED_ABC);
  await page.getByRole('textbox', { name: 'Version name', exact: true }).fill('Later name cannot replace captured intent');
  await page.getByRole('button', { name: 'Save the same version again', exact: true }).click();
  await expect(page.getByRole('link', { name: 'View saved version', exact: true })).toBeVisible();
  const versions = received(await api.GET('/projects/{project_id}/versions', { params: { path } }));
  expect(versions).toHaveLength(2);
  const child = versions.find(value => value.id !== original.id);
  expect(child).toMatchObject({ candidate_id: candidate, name: 'First name after storage failure', parent_version_id: original.id, inputs: { abc: EDITED_ABC, source_score_id: selected } });
  expect(writes).toEqual([{ candidate_id: candidate, name: 'First name after storage failure' }, { candidate_id: candidate, name: 'First name after storage failure' }]);
  await info.attach('storage-failure-captured-save', { body: JSON.stringify({ writes, original, child }, null, 2), contentType: 'application/json' });
});

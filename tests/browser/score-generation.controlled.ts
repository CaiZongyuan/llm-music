test('a lost Version acknowledgement retains the first name, Candidate and parent despite later name edits', async ({ page, baseURL }, info) => {
  const { api, project, score, original } = await withParent(baseURL);
  const selected = await selectEdited(page, project.id, score.id);
  const candidateId = await generateCandidate(page);
  const path = { project_id: project.id };
  const firstName = 'Keep the first submitted name';
  const writes: unknown[] = [];
  let drop = true;
  await page.route(`**/api/projects/${project.id}/versions`, async route => {
    if (route.request().method() !== 'POST') return route.continue();
    writes.push(route.request().postDataJSON());
    const response = await route.fetch();
    if (drop) { drop = false; await route.abort('failed'); }
    else await route.fulfill({ response });
  });
  await page.getByRole('textbox', { name: 'Version name', exact: true }).fill(firstName);
  await page.getByRole('button', { name: 'Save as a version', exact: true }).click();
  await expect(page.locator('.save-candidate .error-box')).toBeVisible();
  const committed = received(await api.GET('/projects/{project_id}/versions', { params: { path } }));
  expect(committed).toHaveLength(2);
  const derived = committed.find(value => value.id !== original.id);
  if (!derived) throw new Error('No durably committed Version before the lost ACK');
  expect(derived).toMatchObject({ name: firstName, candidate_id: candidateId, parent_version_id: original.id });
  await page.getByRole('textbox', { name: 'Version name', exact: true }).fill('A later textbox edit must not change the intent');
  const retry = page.getByRole('button', { name: 'Save the same version again', exact: true });
  await expect(retry).toBeVisible();
  await retry.click();
  await expect(page.getByRole('link', { name: 'View saved version', exact: true })).toBeVisible();
  expect(writes).toEqual([{ candidate_id: candidateId, name: firstName }, { candidate_id: candidateId, name: firstName }]);
  expect(received(await api.GET('/projects/{project_id}/versions', { params: { path } }))).toEqual(committed);
  expect(derived.inputs).toMatchObject({ abc: EDITED_ABC, source_score_id: selected, parent_version_id: original.id });
  await info.attach('captured-version-save', { body: JSON.stringify({ writes, original, derived }, null, 2), contentType: 'application/json' });
});

